export function getPurityBand(purityPct: number): {
  band: PurityBandKey;
  factor: number;
  labelEn: string;
  labelHi: string;
  actionEn: string;
  actionHi: string;
} {
  if (purityPct >= 90) {
    return {
      band: 'full',
      factor: 1.0,
      labelEn: '90%+ (Full Pay)',
      labelHi: '90%+ (पूरा इनाम)',
      actionEn: 'Accept · Full Payout (1.0×)',
      actionHi: 'स्वीकृत · पूरा भुगतान (1.0×)',
    };
  }
  if (purityPct >= 60) {
    return {
      band: 'half',
      factor: 0.5,
      labelEn: '60–89% (Half Pay)',
      labelHi: '60–89% (आधा इनाम)',
      actionEn: 'Reduced Pay (0.5×) · Show Errors',
      actionHi: 'आधा भुगतान (0.5×) · सुधार दिखाएं',
    };
  }
  if (purityPct >= 40) {
    return {
      band: 'low',
      factor: 0.1,
      labelEn: '40–59% (10% Pay)',
      labelHi: '40–59% (10% इनाम)',
      actionEn: 'Minimal Pay (0.1×) · Show Errors',
      actionHi: 'कम भुगतान (0.1×) · सुधार दिखाएं',
    };
  }
  return {
    band: 'reject',
    factor: 0,
    labelEn: '<40% (Rejected)',
    labelHi: '<40% (अस्वीकृत)',
    actionEn: 'Rejected (0×) · Re-sort Required',
    actionHi: 'अस्वीकृत (0×) · दोबारा छांटें',
  };
}

